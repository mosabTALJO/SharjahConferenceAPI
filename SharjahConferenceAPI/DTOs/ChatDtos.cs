namespace SharjahConferenceAPI.DTOs;

using System.Collections.Generic;

/// <summary>
/// Represents an individual chat message in a conversation thread.
/// </summary>
public record ChatMessageDto(
    string Role,
    string Content
);

/// <summary>
/// Request payload for sending a message to the conference AI assistant.
/// </summary>
public class ChatRequestDto
{
    /// <summary>
    /// The user message or question.
    /// </summary>
    public required string Message { get; init; }

    /// <summary>
    /// Optional previous conversation history for multi-turn dialogue context.
    /// </summary>
    public IReadOnlyList<ChatMessageDto>? ConversationHistory { get; init; }

    /// <summary>
    /// Optional language preference hint (e.g., 'en', 'ar'). If not specified, language is auto-detected.
    /// </summary>
    public string? UserLanguage { get; init; }
}

/// <summary>
/// Response payload containing the AI assistant's synthesized reply.
/// </summary>
public class ChatResponseDto
{
    /// <summary>
    /// The synthesized response generated by the AI assistant.
    /// </summary>
    public required string Reply { get; init; }

    /// <summary>
    /// Optional list of tool/function names executed during response generation.
    /// </summary>
    public IReadOnlyList<string>? ToolCallsExecuted { get; init; }
}
